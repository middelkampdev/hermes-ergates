/**
 * Expo config plugin: adopts the UIKit scene life cycle on iOS. An app built
 * with the iOS 27 SDK (Xcode 27) that does not adopt it stops at launch with
 * "UIScene life cycle is required for apps built with this SDK" (Apple
 * TN3187). The Expo SDK 57 template has no scene delegate; SDK 58 generates
 * one itself. Remove this plugin when upgrading to SDK 58: its AppDelegate
 * check then stops the prebuild.
 *
 * It adds a scene manifest to Info.plist and a SceneDelegate.swift that
 * creates the window, starts React Native in it, and passes the links and
 * user activities UIKit now delivers to the scene on to AppDelegate, which
 * hands them to the Expo modules and React Native's Linking as before. It is
 * a reduced copy of Expo SDK 58's ExpoAppSceneDelegate, for what this app
 * uses.
 */
const fs = require('node:fs')
const path = require('node:path')

const { IOSConfig, withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins')

const MARKER = '(plugins/with-scene-lifecycle.js)'
/** The window block of AppDelegate.swift as the Expo SDK 57 template writes it. */
const WINDOW_BLOCK = [
  '#if os(iOS) || os(tvOS)',
  '    window = UIWindow(frame: UIScreen.main.bounds)',
  '    factory.startReactNative(',
  '      withModuleName: "main",',
  '      in: window,',
  '      launchOptions: launchOptions)',
  '#endif',
  '',
  '',
].join('\n')

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default Configuration',
        UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
      },
    ],
  },
}

const SCENE_DELEGATE = `// Generated by plugins/with-scene-lifecycle.js: the iOS 27 SDK requires the
// UIKit scene life cycle. Under it UIKit sends the window, links and user
// activities to this delegate instead of AppDelegate.
internal import Expo
import React
import UIKit

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else {
      return
    }
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory else {
      fatalError("SceneDelegate needs the React Native factory that AppDelegate creates at launch.")
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // expo-system-ui reads the window from the app delegate.
    appDelegate.window = window

    // Linking.getInitialURL() reads the link that started the app from the
    // launch options; under the scene life cycle it comes in connectionOptions.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any]?
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions = [UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey"): url]
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)

    connectionOptions.urlContexts.forEach { open($0) }
    connectionOptions.userActivities.forEach { self.scene(scene, continue: $0) }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    URLContexts.forEach { open($0) }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = UIApplication.shared.delegate?.application?(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }

  private func open(_ context: UIOpenURLContext) {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [.openInPlace: context.options.openInPlace]
    options[.sourceApplication] = context.options.sourceApplication
    options[.annotation] = context.options.annotation
    _ = UIApplication.shared.delegate?.application?(UIApplication.shared, open: context.url, options: options)
  }
}
`

/** AppDelegate.swift without the window block: SceneDelegate creates the window. */
function applySceneLifecycle(appDelegate) {
  if (appDelegate.includes(MARKER)) return appDelegate
  if (appDelegate.split(WINDOW_BLOCK).length !== 2) {
    throw new Error(
      'AppDelegate.swift does not create the window and start React Native the way plugins/with-scene-lifecycle.js expects. If this Expo SDK generates its own SceneDelegate (SDK 58 and later), remove the plugin; otherwise compare AppDelegate.swift with the Expo template and update it.'
    )
  }
  return appDelegate.replace(
    WINDOW_BLOCK,
    `    // SceneDelegate creates the window and starts React Native in it\n    // ${MARKER}.\n`
  )
}

function withSceneLifecycle(config) {
  config = withInfoPlist(config, next => {
    next.modResults.UIApplicationSceneManifest = SCENE_MANIFEST
    return next
  })
  config = withAppDelegate(config, next => {
    if (next.modResults.language !== 'swift') {
      throw new Error('plugins/with-scene-lifecycle.js expects a Swift AppDelegate.')
    }
    next.modResults.contents = applySceneLifecycle(next.modResults.contents)
    return next
  })
  config = withDangerousMod(config, [
    'ios',
    next => {
      const { platformProjectRoot, projectName } = next.modRequest
      fs.writeFileSync(path.join(platformProjectRoot, projectName, 'SceneDelegate.swift'), SCENE_DELEGATE)
      return next
    },
  ])
  config = withXcodeProject(config, next => {
    const { projectName } = next.modRequest
    const filepath = `${projectName}/SceneDelegate.swift`
    if (!next.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: next.modResults })
    }
    return next
  })
  return config
}

module.exports = withSceneLifecycle
module.exports.applySceneLifecycle = applySceneLifecycle
module.exports.SCENE_DELEGATE = SCENE_DELEGATE
module.exports.SCENE_MANIFEST = SCENE_MANIFEST
